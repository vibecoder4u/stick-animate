from __future__ import annotations

import hashlib
import json
from pathlib import Path

root = Path("output")
plan_path = root / "script-only-psychology-scene-plan.json"
plan = json.loads(plan_path.read_text(encoding="utf-8"))
meta = plan.get("design_metadata", {})
assert meta.get("provider") == "groq", f"Expected live Groq planning, got {meta.get('provider')!r}"
assert meta.get("creative_mode") == "ai", f"Expected AI creative mode, got {meta.get('creative_mode')!r}"
assert meta.get("api_requests") == 1, f"Expected exactly one planning request, got {meta.get('api_requests')!r}"
scenes = plan.get("scenes", [])
assert len(scenes) >= 1, "Groq returned no scenes"
overlays = [item for scene in scenes for item in scene.get("visual_overlays", [])]
custom_designs = [item for item in overlays if isinstance(item.get("visual_design") or item.get("drawing_blueprint"), dict)]
assert custom_designs, "Groq did not invent any new vector concepts in its scene plan"
print(f"Groq created {len(scenes)} scenes, {len(overlays)} overlays and {len(custom_designs)} custom vector blueprints.")

manifest_path = root / "visual-library-manifest.json"
manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
assets = manifest.get("assets", {})
generated = [(asset_id, item) for asset_id, item in assets.items()
             if item.get("kind") == "generated_concept"]
assert generated, "No AI-authored concept SVGs were generated by the local drawing engine"
for asset_id, item in generated:
    digest = item.get("sha256", "")
    assert len(digest) == 64, f"Invalid SHA-256 for {asset_id}"
    svg_path = root / item["path"]
    assert svg_path.is_file(), f"Missing generated SVG for {asset_id}: {svg_path}"
    actual = hashlib.sha256(svg_path.read_bytes()).hexdigest()
    assert actual == digest, f"SVG content hash mismatch for {asset_id}"
print("Verified generated SVG assets:")
for asset_id, item in generated:
    print(f"  {asset_id} -> {item['sha256']} ({item['path']})")
